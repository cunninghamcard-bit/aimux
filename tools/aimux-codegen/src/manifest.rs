//! `manifest.json` and the coverage report (phase 2 unit 2.1; #200 §6.5,
//! RFC-0042 §7.2–7.3).
//!
//! The manifest records the AI SDK baseline read from
//! `fixtures/aisdk/VERSIONS.json` at generation time (D11 default a), the
//! generator version, a hash of every input, a schema revision and the type
//! model extracted from `aimux-core/src` ([`crate::extract`]).
//!
//! The coverage report lists `<name> <category> <source>` for every manifest
//! type; it must equal the `[exported]` section of
//! `docs/plan/closure-dtos.txt` (the 1.5 closure DTO list). Any missing or
//! extra line fails generation and `--check`.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde::Serialize;
use sha2::{Digest, Sha256};

use crate::Output;
use crate::extract::{AliasDef, TypeDef, extract};

/// Bumped when the manifest layout changes.
pub const SCHEMA_REVISION: u32 = 1;

/// Where the manifest inputs live.
#[derive(Debug, Clone)]
pub struct Inputs {
    /// `aimux-core/src`.
    pub src_root: PathBuf,
    /// `fixtures/aisdk/VERSIONS.json`.
    pub versions: PathBuf,
    /// `docs/plan/closure-dtos.txt`.
    pub list: PathBuf,
}

impl Inputs {
    /// Default inputs relative to the workspace root.
    #[must_use]
    pub fn from_workspace(root: &Path) -> Self {
        Self {
            src_root: root.join("aimux-core/src"),
            versions: root.join("fixtures/aisdk/VERSIONS.json"),
            list: root.join("docs/plan/closure-dtos.txt"),
        }
    }
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct Manifest<'a> {
    schema_revision: u32,
    generator: Generator,
    sdk: BTreeMap<String, String>,
    input_hash: String,
    types: &'a [TypeDef],
    auxiliary_types: &'a [TypeDef],
    aliases: &'a BTreeMap<String, AliasDef>,
}

#[derive(Serialize)]
struct Generator {
    name: &'static str,
    version: &'static str,
}

pub const SRC_PREFIX: &str = "aimux-core/src";

/// Manifest and coverage outputs (`manifest.json`, `coverage.txt`).
///
/// # Errors
///
/// Extraction errors, an unreadable/invalid VERSIONS.json or list, and one
/// message per coverage difference (`missing from manifest: ..` /
/// `not in closure-dtos.txt: ..`).
pub fn generate(inputs: &Inputs) -> Result<Vec<Output>, Vec<String>> {
    let model = extract(&inputs.src_root, SRC_PREFIX)?;
    let types = &model.types;
    let versions_text = std::fs::read_to_string(&inputs.versions)
        .map_err(|e| vec![format!("{}: {e}", inputs.versions.display())])?;
    let sdk: BTreeMap<String, String> = serde_json::from_str(&versions_text)
        .map_err(|e| vec![format!("{}: {e}", inputs.versions.display())])?;
    let coverage = coverage_lines(types);
    let list_text = std::fs::read_to_string(&inputs.list)
        .map_err(|e| vec![format!("{}: {e}", inputs.list.display())])?;
    compare(&coverage, &exported_section(&list_text))?;

    let manifest = Manifest {
        schema_revision: SCHEMA_REVISION,
        generator: Generator {
            name: env!("CARGO_PKG_NAME"),
            version: env!("CARGO_PKG_VERSION"),
        },
        sdk,
        input_hash: input_hash(inputs, &versions_text)?,
        types,
        auxiliary_types: &model.auxiliary_types,
        aliases: &model.aliases,
    };
    let mut json = serde_json::to_string_pretty(&manifest).map_err(|e| vec![e.to_string()])?;
    json.push('\n');
    let mut report = String::from(
        "# Manifest coverage (unit 2.1). Generated by aimux-codegen; must equal the\n# [exported] section of docs/plan/closure-dtos.txt.\n",
    );
    for line in &coverage {
        report.push_str(line);
        report.push('\n');
    }
    Ok(vec![
        Output {
            path: PathBuf::from("manifest.json"),
            content: json,
        },
        Output {
            path: PathBuf::from("coverage.txt"),
            content: report,
        },
    ])
}

/// `<name> <category> <source>` per type, sorted.
#[must_use]
pub fn coverage_lines(types: &[TypeDef]) -> Vec<String> {
    let mut lines: Vec<String> = types
        .iter()
        .map(|t| format!("{} {} {}", t.name, t.category, t.source))
        .collect();
    lines.sort();
    lines
}

/// Lines of the `[exported]` section of closure-dtos.txt.
#[must_use]
pub fn exported_section(text: &str) -> Vec<String> {
    let mut lines = Vec::new();
    let mut inside = false;
    for line in text.lines() {
        if line.starts_with('[') {
            inside = line.starts_with("[exported]");
            continue;
        }
        if inside && !line.trim().is_empty() && !line.starts_with('#') {
            lines.push(line.trim().to_string());
        }
    }
    lines.sort();
    lines
}

/// Equal sets, or one message per difference.
///
/// # Errors
///
/// `missing from manifest: <line>` for list lines the manifest lacks and
/// `not in closure-dtos.txt: <line>` for extra manifest types.
pub fn compare(coverage: &[String], list: &[String]) -> Result<(), Vec<String>> {
    let mut problems = Vec::new();
    for l in list {
        if !coverage.contains(l) {
            problems.push(format!("coverage: missing from manifest: {l}"));
        }
    }
    for c in coverage {
        if !list.contains(c) {
            problems.push(format!("coverage: not in closure-dtos.txt: {c}"));
        }
    }
    if problems.is_empty() {
        Ok(())
    } else {
        Err(problems)
    }
}

fn input_hash(inputs: &Inputs, versions_text: &str) -> Result<String, Vec<String>> {
    let mut files = Vec::new();
    collect(&inputs.src_root, &mut files).map_err(|e| vec![e])?;
    files.sort();
    let mut h = Sha256::new();
    for f in files {
        let rel = f
            .strip_prefix(&inputs.src_root)
            .unwrap_or(&f)
            .to_string_lossy()
            .replace('\\', "/");
        let bytes = lf(&std::fs::read(&f).map_err(|e| vec![format!("{}: {e}", f.display())])?);
        h.update(format!("{SRC_PREFIX}/{rel}\0{}\0", bytes.len()));
        h.update(bytes);
    }
    h.update("fixtures/aisdk/VERSIONS.json\0");
    h.update(lf(versions_text.as_bytes()));
    Ok(format!("sha256:{:x}", h.finalize()))
}

/// CRLF → LF, so the hash (and the manifest) is the same whatever line
/// endings the checkout produced (e.g. `core.autocrlf=true` on Windows).
/// Done here rather than via `.gitattributes`, which only applies to
/// checkouts that honour it.
#[must_use]
pub fn lf(bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'\r' && bytes.get(i + 1) == Some(&b'\n') {
            i += 1;
            continue;
        }
        out.push(bytes[i]);
        i += 1;
    }
    out
}

fn collect(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), String> {
    for entry in std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))? {
        let p = entry.map_err(|e| e.to_string())?.path();
        if p.is_dir() {
            collect(&p, out)?;
        } else if p.extension().is_some_and(|x| x == "rs") {
            out.push(p);
        }
    }
    Ok(())
}

/// Write `manifest.json` and `coverage.txt` under `out_dir`. Nothing is
/// written when generation fails.
///
/// # Errors
///
/// See [`generate`]; plus I/O errors.
pub fn write(inputs: &Inputs, out_dir: &Path) -> Result<(), Vec<String>> {
    for o in generate(inputs)? {
        let path = out_dir.join(&o.path);
        std::fs::write(&path, o.content).map_err(|e| vec![format!("{}: {e}", path.display())])?;
    }
    Ok(())
}

/// Compare committed `manifest.json` / `coverage.txt` under `out_dir` with a
/// fresh generation (D8 `--check`).
///
/// # Errors
///
/// Generation/coverage errors, or one `<path> is out of date` per stale or
/// missing file.
pub fn check(inputs: &Inputs, out_dir: &Path) -> Result<(), Vec<String>> {
    let mut problems = Vec::new();
    for o in generate(inputs)? {
        let path = out_dir.join(&o.path);
        match std::fs::read_to_string(&path) {
            Ok(t) if t == o.content => {}
            Ok(_) => problems.push(format!("{} is out of date", path.display())),
            Err(e) => problems.push(format!("{}: {e}", path.display())),
        }
    }
    if problems.is_empty() {
        Ok(())
    } else {
        Err(problems)
    }
}
