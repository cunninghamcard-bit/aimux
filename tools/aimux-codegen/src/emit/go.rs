struct Gen {
    names: BTreeSet<String>,
    out: String,
    /// Fixed string values used as field types ([`WireTy::Literal`]).
    literals: std::cell::RefCell<BTreeSet<String>>,
    /// String-enum type → the wire value a custom `skip_serializing_if`
    /// leaves out ([`WireField::skip_value`]).
    skips: BTreeMap<String, String>,
}

/// Go type name of a fixed-string field.
fn literal_name(lit: &str) -> String {
    format!("Lit{}", pascal(lit))
}

/// `snake_case` / `kebab-case` / `camelCase` text → `PascalCase` identifier.
#[must_use]
pub fn pascal(s: &str) -> String {
    let mut out = String::new();
    let mut up = true;
    for ch in s.chars() {
        if ch.is_ascii_alphanumeric() {
            if up {
                out.extend(ch.to_uppercase());
            } else {
                out.push(ch);
            }
            up = false;
        } else {
            up = true;
        }
    }
    if out.is_empty() || out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, 'X');
    }
    out
}

/// Tab-indented lines with columns padded the way gofmt aligns
/// consecutive struct fields and const specs (cell width + one space; the
/// last column is not padded).
fn align(rows: &[Vec<String>]) -> String {
    let cols = rows.iter().map(Vec::len).max().unwrap_or(0);
    let mut width = vec![0; cols];
    for r in rows {
        for (i, c) in r.iter().enumerate() {
            width[i] = width[i].max(c.chars().count());
        }
    }
    let mut out = String::new();
    for r in rows {
        out.push('\t');
        for (i, c) in r.iter().enumerate() {
            out.push_str(c);
            if i + 1 < r.len() {
                out.push_str(&" ".repeat(width[i] - c.chars().count() + 1));
            }
        }
        out.push('\n');
    }
    out
}

fn go_str(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_default()
}

fn uniq(used: &mut BTreeSet<String>, base: String) -> String {
    let mut name = base.clone();
    let mut i = 2;
    while !used.insert(name.clone()) {
        name = format!("{base}{i}");
        i += 1;
    }
    name
}

impl Gen {
    fn w(&mut self, s: &str) {
        self.out.push_str(s);
    }

    fn prim(p: &str) -> &'static str {
        match p {
            "bool" => "bool",
            "u8" => "uint8",
            "u16" => "uint16",
            "u32" => "uint32",
            "u64" | "usize" => "uint64",
            "i8" => "int8",
            "i16" => "int16",
            "i32" => "int32",
            "i64" | "isize" => "int64",
            "u128" | "i128" => "json.Number",
            "f32" => "float32",
            "f64" => "float64",
            _ => "string",
        }
    }

    fn go_ty(&self, t: &WireTy) -> String {
        match t {
            WireTy::Prim(p) => Self::prim(p).into(),
            WireTy::Json | WireTy::Tuple(_) => "json.RawMessage".into(),
            WireTy::Array(i) if matches!(i.as_ref(), WireTy::Prim(p) if p == "u8") => "[]U8".into(),
            WireTy::Array(i) => format!("[]{}", self.go_ty(i)),
            WireTy::Map { value, .. } => format!("map[string]{}", self.go_ty(value)),
            WireTy::Named(n) if self.names.contains(n) => n.clone(),
            WireTy::Named(_) => "json.RawMessage".into(),
            WireTy::Nullable(i) => format!("*{}", self.go_ty(i)),
            WireTy::Literal(lit) => {
                self.literals.borrow_mut().insert(lit.clone());
                literal_name(lit)
            }
        }
    }

    /// `IsZero` for each string enum a custom `skip_serializing_if` skips
    /// (`omitzero`): the skipped value, and `""` (an absent key decodes to
    /// `""`, which serde reads as the `default`, the same skipped value).
    fn skip_methods(&mut self) {
        for (n, v) in std::mem::take(&mut self.skips) {
            let q = go_str(&v);
            let _ = write!(
                self.out,
                "\n// IsZero reports whether serde leaves {n} out: {q} (custom skip_serializing_if), or unset.\nfunc (x {n}) IsZero() bool {{ return x == \"\" || x == {q} }}\n"
            );
        }
    }

    /// One empty struct per fixed string: its zero value marshals as the
    /// string, and decoding accepts only that string.
    fn literal_types(&mut self) {
        let lits = self.literals.borrow().clone();
        for lit in lits {
            let n = literal_name(&lit);
            let q = go_str(&lit);
            let _ = write!(
                self.out,
                "\n// {n} is the fixed wire value {q}: always written, and decoding accepts only {q}.\ntype {n} struct{{}}\n\nfunc ({n}) MarshalJSON() ([]byte, error) {{ return []byte(`{q}`), nil }}\n\nfunc (*{n}) UnmarshalJSON(b []byte) error {{\n\tvar s string\n\tif err := json.Unmarshal(b, &s); err != nil || s != {q} {{\n\t\treturn fmt.Errorf(\"expected type %s, found %s\", {qq}, b)\n\t}}\n\treturn nil\n}}\n",
                qq = go_str(&q),
            );
        }
    }

    fn ty(&mut self, t: &WireType) {
        let _ = write!(self.out, "\n// {} mirrors {}.\n", t.name, t.doc_source);
        match &t.body {
            WireBody::Record { fields } => self.record(&t.name, fields),
            WireBody::Alias(inner) => {
                let g = self.go_ty(inner);
                let eq = matches!(inner, WireTy::Named(_) | WireTy::Json | WireTy::Tuple(_));
                let _ = writeln!(
                    self.out,
                    "type {} {}{g}",
                    t.name,
                    if eq { "= " } else { "" }
                );
            }
            WireBody::StringEnum { values, open } => self.string_enum(&t.name, values, *open),
            WireBody::Union { repr, variants } => self.union(&t.name, repr, variants),
        }
    }

    fn record(&mut self, name: &str, fields: &[WireField]) {
        if fields.iter().any(|f| f.default_fn.is_some()) {
            let _ = writeln!(
                self.out,
                "//\n// {name} implements UnmarshalJSON (to preset its #[serde(default = \"fn\")]\n// values). Embedding it in another struct promotes that method and\n// swallows the outer struct's fields: do not embed it."
            );
        }
        let _ = writeln!(self.out, "type {name} struct {{");
        let mut used = BTreeSet::new();
        let mut rows = Vec::new();
        let mut defaults = Vec::new();
        for f in fields {
            let ident = uniq(&mut used, pascal(&f.rust));
            if let Some(d) = &f.default_fn
                && let Some((_, v)) = DEFAULT_FNS.iter().find(|(k, _)| k == d)
            {
                defaults.push(format!("{ident}: {v}"));
            }
            let inner = self.go_ty(&f.ty);
            let (ty, opt) = if f.presence.tri_state {
                (format!("TriState[{inner}]"), ",omitzero")
            } else if f.presence.nullable {
                (
                    format!("*{inner}"),
                    if f.presence.skip_if_empty {
                        ",omitempty"
                    } else {
                        ""
                    },
                )
            } else {
                (
                    inner,
                    if f.presence.skip_if_empty {
                        ",omitempty"
                    } else {
                        ""
                    },
                )
            };
            let opt = match (&f.skip_value, &f.ty) {
                (Some(v), WireTy::Named(n)) => {
                    // `omitzero` calls the type's IsZero (skip_methods).
                    let prev = self.skips.insert(n.clone(), v.clone());
                    assert!(
                        prev.is_none_or(|p| p == *v),
                        "{name}.{}: {n} skipped at two different values",
                        f.wire
                    );
                    ",omitzero"
                }
                (Some(_), _) => panic!(
                    "{name}.{}: a custom skip_serializing_if needs a string-enum type",
                    f.wire
                ),
                (None, _) => opt,
            };
            rows.push(vec![ident, ty, format!("`json:\"{}{opt}\"`", f.wire)]);
        }
        self.w(&align(&rows));
        self.w("}\n");
        let required: Vec<String> = fields
            .iter()
            .filter(|f| !f.presence.omittable && !f.presence.nullable)
            .map(|f| go_str(&f.wire))
            .collect();
        let _ = writeln!(
            self.out,
            "\nfunc ({name}) wireRequired() []string {{\n\treturn []string{{{}}}\n}}",
            required.join(", ")
        );
        if !defaults.is_empty() {
            let _ = write!(
                self.out,
                "\n// UnmarshalJSON presets the #[serde(default = \"fn\")] values.\nfunc (x *{name}) UnmarshalJSON(b []byte) error {{\n\ttype plain {name}\n\tp := plain{{{}}}\n\tif err := decodeWithDefaults(b, &p); err != nil {{\n\t\treturn err\n\t}}\n\t*x = {name}(p)\n\treturn nil\n}}\n",
                defaults.join(", ")
            );
        }
    }

    fn string_enum(&mut self, name: &str, values: &[String], open: bool) {
        let _ = writeln!(self.out, "type {name} string\n\nconst (");
        let mut used = BTreeSet::new();
        let mut rows = Vec::new();
        for v in values {
            let c = uniq(&mut used, format!("{name}{}", pascal(v)));
            rows.push(vec![c, name.to_string(), format!("= {}", go_str(v))]);
        }
        self.w(&align(&rows));
        self.w(")\n");
        if open {
            return;
        }
        let list: Vec<String> = values.iter().map(|v| go_str(v)).collect();
        let _ = write!(
            self.out,
            "\nfunc (x *{name}) UnmarshalJSON(b []byte) error {{\n\tvar s string\n\tif err := json.Unmarshal(b, &s); err != nil {{\n\t\treturn err\n\t}}\n\tswitch s {{\n\tcase {}:\n\t\t*x = {name}(s)\n\t\treturn nil\n\t}}\n\treturn fmt.Errorf(\"{name}: unknown value %q\", s)\n}}\n",
            list.join(", ")
        );
    }

    /// Payload Go type and a declaration for struct variants.
    fn variant_ty(&mut self, union: &str, v: &crate::wire::WireVariant) -> Option<String> {
        match &v.body {
            VariantBody::Unit => None,
            VariantBody::Value(t) => Some(self.go_ty(t)),
            VariantBody::Tuple(_) => Some("json.RawMessage".into()),
            VariantBody::Fields(fields) => {
                let mut name = format!("{union}{}", pascal(&v.rust));
                if self.names.contains(&name) {
                    name.push_str("Variant");
                }
                let _ = write!(
                    self.out,
                    "\n// {name} is the {} variant of {union}.\n",
                    v.rust
                );
                self.record(&name, fields);
                Some(name)
            }
        }
    }

    fn union(&mut self, name: &str, repr: &UnionRepr, variants: &[crate::wire::WireVariant]) {
        let untagged_all = matches!(repr, UnionRepr::Untagged);
        if untagged_all {
            let _ = writeln!(
                self.out,
                "// Untagged: decoding tries the variants in declaration order.\ntype {name} struct {{\n\tVariant string\n\tValue   any\n\tRaw     json.RawMessage\n}}"
            );
        } else {
            let _ = writeln!(
                self.out,
                "// Tagged union ({repr:?}); Value holds the variant payload (nil for unit variants).\ntype {name} struct {{\n\tTag   string\n\tValue any\n\tRaw   json.RawMessage\n}}"
            );
        }
        let mut payload: Vec<Option<String>> = Vec::new();
        for v in variants {
            payload.push(self.variant_ty(name, v));
        }
        // Strict tries, in declaration order (untagged unions).
        let tries = || {
            let mut s = String::new();
            for (v, p) in variants.iter().zip(&payload) {
                match p {
                    None => {
                        let _ = write!(
                            s,
                            "\tif isNull(b) {{\n\t\tx.Variant, x.Value = {}, nil\n\t\treturn nil\n\t}}\n",
                            go_str(&v.rust)
                        );
                    }
                    Some(t) => {
                        let _ = write!(
                            s,
                            "\t{{\n\t\tvar v {t}\n\t\tif decodeStrict(b, &v) == nil {{\n\t\t\tx.Variant, x.Value = {}, v\n\t\t\treturn nil\n\t\t}}\n\t}}\n",
                            go_str(&v.rust)
                        );
                    }
                }
            }
            s
        };
        if untagged_all {
            let body = tries();
            let _ = write!(
                self.out,
                "\nfunc (x *{name}) UnmarshalJSON(b []byte) error {{\n\tx.Raw = clone(b)\n{body}\treturn fmt.Errorf(\"{name}: no variant matches %s\", b)\n}}\n\nfunc (x {name}) MarshalJSON() ([]byte, error) {{\n\tif x.Value == nil {{\n\t\treturn []byte(\"null\"), nil\n\t}}\n\treturn json.Marshal(x.Value)\n}}\n"
            );
            return;
        }
        // Tagged: decode payload bytes `p` by tag.
        let mut cases = String::new();
        let mut other = None;
        for (v, p) in variants.iter().zip(&payload) {
            let Some(wire) = &v.wire else { continue };
            if v.other {
                other = Some(wire.clone());
            }
            let mut tags = vec![go_str(wire)];
            tags.extend(v.aliases.iter().map(|a| go_str(a)));
            let decode = match p {
                None => "\t\tx.Value = nil\n".to_string(),
                Some(t) => format!(
                    "\t\tvar v {t}\n\t\tif err := json.Unmarshal(p, &v); err != nil {{\n\t\t\treturn fmt.Errorf(\"{name}.{}: %w\", err)\n\t\t}}\n\t\tx.Value = v\n",
                    v.rust
                ),
            };
            let _ = write!(
                cases,
                "\tcase {}:\n\t\tx.Tag = {}\n{decode}\t\treturn nil\n",
                tags.join(", "),
                go_str(wire)
            );
        }
        // Variant-level `#[serde(untagged)]` inside a tagged enum is not
        // used in aimux-core; such a value fails to decode here.
        let fallback = if let Some(o) = &other {
            format!("\tx.Tag, x.Value = {}, nil\n\treturn nil\n", go_str(o))
        } else {
            format!("\treturn fmt.Errorf(\"{name}: unknown tag %q\", tag)\n")
        };
        let (head, marshal) = match repr {
            UnionRepr::Internal { tag } => (
                format!(
                    "\ttag, ok := tagOf(b, {k})\n\tif !ok {{\n\t\ttag = \"\"\n\t}}\n\tp := b\n",
                    k = go_str(tag)
                ),
                format!(
                    "\tp, err := marshalPayload(x.Value)\n\tif err != nil {{\n\t\treturn nil, err\n\t}}\n\treturn withTag({}, x.Tag, p)\n",
                    go_str(tag)
                ),
            ),
            UnionRepr::Adjacent { tag, content } => (
                format!(
                    "\tvar env struct {{\n\t\tTag     *string         `json:{}`\n\t\tContent json.RawMessage `json:{}`\n\t}}\n\tif err := json.Unmarshal(b, &env); err != nil {{\n\t\treturn err\n\t}}\n\ttag := \"\"\n\tif env.Tag != nil {{\n\t\ttag = *env.Tag\n\t}}\n\tp := []byte(env.Content)\n",
                    go_str(tag),
                    go_str(content)
                ),
                format!(
                    "\tp, err := marshalPayload(x.Value)\n\tif err != nil {{\n\t\treturn nil, err\n\t}}\n\tenv := map[string]json.RawMessage{{}}\n\tt, _ := json.Marshal(x.Tag)\n\tenv[{}] = t\n\tif p != nil {{\n\t\tenv[{}] = p\n\t}}\n\treturn json.Marshal(env)\n",
                    go_str(tag),
                    go_str(content)
                ),
            ),
            _ => (
                "\tvar tag string\n\tvar p []byte\n\tif json.Unmarshal(b, &tag) != nil {\n\t\tvar obj map[string]json.RawMessage\n\t\tif err := json.Unmarshal(b, &obj); err != nil || len(obj) != 1 {\n\t\t\ttag = \"\"\n\t\t}\n\t\tfor k, v := range obj {\n\t\t\ttag, p = k, v\n\t\t}\n\t}\n".to_string(),
                "\tif x.Value == nil {\n\t\treturn json.Marshal(x.Tag)\n\t}\n\tp, err := json.Marshal(x.Value)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn json.Marshal(map[string]json.RawMessage{x.Tag: p})\n".to_string(),
            ),
        };
        let _ = write!(
            self.out,
            "\nfunc (x *{name}) UnmarshalJSON(b []byte) error {{\n\tx.Raw = clone(b)\n{head}\t_ = p\n\tswitch tag {{\n{cases}\t}}\n{fallback}}}\n\nfunc (x {name}) MarshalJSON() ([]byte, error) {{\n{marshal}}}\n"
        );
    }
}
