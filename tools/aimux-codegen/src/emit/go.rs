//! Go emitter (unit 2.2).
//!
//! Mapping:
//! - Record → struct with `json` tags. `omitempty` only when the Rust field
//!   has `skip_serializing_if`; a nullable field is a pointer; a tri-state
//!   field is `TriState[T]` with `omitzero` (absent / null / value).
//! - StringEnum → `type X string` plus constants; a closed enum rejects
//!   unknown values on decode.
//! - Tagged Union → wrapper `{Tag, Value, Raw}` whose `UnmarshalJSON`
//!   dispatches on the tag (internal / adjacent / external); `MarshalJSON`
//!   writes the tag back.
//! - Untagged Union → wrapper `{Variant, Value, Raw}`; `UnmarshalJSON`
//!   tries the variants in declaration order with a strict decode (JSON kind
//!   and required keys must match, as serde's untagged decoding requires).
//! - `Vec<u8>` → `[]U8` (a JSON array of numbers, not Go's base64 `[]byte`);
//!   tuples, opaque JSON and u128/i128 → `json.RawMessage` / `json.Number`.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::PathBuf;

use super::Emitter;
use crate::Output;
use crate::wire::{UnionRepr, VariantBody, WireBody, WireField, WireModel, WireTy, WireType};

/// The Go emitter.
#[derive(Debug, Default, Clone, Copy)]
pub struct Go;

/// Go package name of the generated code.
pub const PACKAGE: &str = "wire";

impl Emitter for Go {
    fn lang(&self) -> &'static str {
        "go"
    }

    fn check(&self, model: &WireModel) -> Result<(), Vec<String>> {
        Go::check(model)
    }

    fn emit(&self, model: &WireModel) -> Vec<Output> {
        let names: BTreeSet<String> = model.types.iter().map(|t| t.name.clone()).collect();
        let mut g = Gen {
            names,
            out: String::new(),
            literals: std::cell::RefCell::default(),
            skips: BTreeMap::new(),
        };
        g.out.push_str(HEADER);
        for t in &model.types {
            g.ty(t);
        }
        g.literal_types();
        g.skip_methods();
        vec![
            Output {
                path: PathBuf::from("go.mod"),
                content: "module aimux.dev/codegen-out/go\n\ngo 1.24\n".into(),
            },
            Output {
                path: PathBuf::from("runtime.go"),
                content: RUNTIME.into(),
            },
            Output {
                path: PathBuf::from("types.go"),
                content: g.out,
            },
        ]
    }
}

/// `#[serde(default = "path")]` functions, by last path segment, with the
/// Go value each returns (the same table as `swift::DEFAULT_FNS`). Any other
/// function is a generation error ([`Go::check`]): Go would decode the zero
/// value where serde calls the function.
pub const DEFAULT_FNS: &[(&str, &str)] = &[
    // aimux-core/src/video_model.rs:220 `fn default_video_n() -> u32 { 1 }`.
    ("default_video_n", "1"),
    // aimux-core/src/recording.rs:346 `fn default_finalized() -> bool { true }`.
    ("default_finalized", "true"),
    // aimux-core/src/moa.rs:60 `fn default_moa_provider() -> String { "moa".into() }`.
    ("default_moa_provider", "\"moa\""),
    // aimux-core/src/moa.rs:64 `fn default_strip_reference_tools() -> bool { true }`.
    ("default_strip_reference_tools", "true"),
];

impl Go {
    /// Every `default = "fn"` field has a registered Go value, on a field
    /// Go can preset (not nullable, not tri-state).
    ///
    /// # Errors
    ///
    /// One message per unregistered or unpresettable default fn.
    pub fn check(model: &WireModel) -> Result<(), Vec<String>> {
        let mut errs = Vec::new();
        for t in &model.types {
            let fields: Vec<&WireField> = match &t.body {
                WireBody::Record { fields } => fields.iter().collect(),
                WireBody::Union { variants, .. } => variants
                    .iter()
                    .flat_map(|v| match &v.body {
                        VariantBody::Fields(f) => f.iter().collect(),
                        _ => vec![],
                    })
                    .collect(),
                _ => vec![],
            };
            for f in fields {
                let Some(d) = &f.default_fn else { continue };
                if !DEFAULT_FNS.iter().any(|(k, _)| k == d) {
                    errs.push(format!(
                        "{}.{}: #[serde(default = \"{d}\")] is not in go::DEFAULT_FNS; Go would decode the zero value",
                        t.name, f.wire
                    ));
                } else if f.presence.nullable || f.presence.tri_state {
                    errs.push(format!(
                        "{}.{}: default fn on a nullable field; the Go emitter cannot preset it",
                        t.name, f.wire
                    ));
                }
            }
        }
        if errs.is_empty() { Ok(()) } else { Err(errs) }
    }
}

