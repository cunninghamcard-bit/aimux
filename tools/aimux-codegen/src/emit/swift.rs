//! Swift emitter (unit 2.2), per `docs/plan/2.2-swift-mapping.md`.
//!
//! Mapping:
//! - Record → `struct` with explicit `CodingKeys`, hand-emitted
//!   `init(from:)` / `encode(to:)`. Presence: required → `decode`/`encode`;
//!   omittable (`default`) → `contains ? decode : default` (a present `null`
//!   is rejected, as serde does); `Option` without skip → `encodeNil` for
//!   `nil` (serde writes `null`); `Option` with skip → `encodeIfPresent`;
//!   tri-state (a codec) → `TriState<T>`; `skip_if_empty` → written only
//!   when not empty.
//! - StringEnum → closed `enum X: String`; open (`#[serde(other)]`) → a
//!   `RawRepresentable` struct that keeps the received string.
//! - Union → `indirect enum` with a hand-emitted coder per representation
//!   (internal / external / adjacent / untagged, untagged strict in
//!   declaration order). Struct variants get a top-level payload struct
//!   `<Union><Variant>` (Go's naming).
//! - `Json` / `Tuple` / unknown `Named` → `JSONValue`
//!   (Bool → Int64 → UInt64 → Double); `Vec<u8>` → `WireBytes = [UInt8]`.
//! - `u128` / `i128`, a variant-level untagged variant inside a tagged
//!   enum, and a by-value struct cycle are emitter errors ([`Swift::check`]).

