/// The Swift emitter.
#[derive(Debug, Default, Clone, Copy)]
pub struct Swift;

/// SwiftPM module name of the generated code.
pub const MODULE: &str = "AimuxWire";

/// Header line of every generated Swift file.
pub const HEADER: &str = "// Code generated by aimux-codegen (tools/aimux-codegen). DO NOT EDIT.";

impl Emitter for Swift {
    fn lang(&self) -> &'static str {
        "swift"
    }

    fn check(&self, model: &WireModel) -> Result<(), Vec<String>> {
        Swift::check(model)
    }

    fn emit(&self, model: &WireModel) -> Vec<Output> {
        let mut g = Gen::new(model);
        g.out.push_str(HEADER);
        g.out.push_str("\n\nimport Foundation\n");
        for t in &model.types {
            g.ty(t);
        }
        g.literal_types();
        let src = |f: &str| PathBuf::from("Sources").join(MODULE).join(f);
        vec![
            Output {
                path: PathBuf::from("Package.swift"),
                content: format!(
                    "// swift-tools-version:5.9\n{HEADER}\nimport PackageDescription\n\nlet package = Package(\n    name: \"{MODULE}\",\n    products: [.library(name: \"{MODULE}\", targets: [\"{MODULE}\"])],\n    targets: [.target(name: \"{MODULE}\")]\n)\n"
                ),
            },
            Output {
                path: src("Runtime.swift"),
                content: format!("{HEADER}\n{RUNTIME}"),
            },
            Output {
                path: src("Types.swift"),
                content: g.out,
            },
        ]
    }
}

/// `#[serde(default = "path")]` functions, by last path segment, with the
/// Swift value each returns. Any other function is an emitter error
/// ([`Swift::check`]): the Swift default would otherwise be guessed.
pub const DEFAULT_FNS: &[(&str, &str)] = &[
    // aimux-core/src/video_model.rs:220 `fn default_video_n() -> u32 { 1 }`.
    ("default_video_n", "1"),
    // aimux-core/src/recording.rs:346 `fn default_finalized() -> bool { true }`.
    ("default_finalized", "true"),
    // aimux-core/src/moa.rs:60 `fn default_moa_provider() -> String { "moa".into() }`.
    ("default_moa_provider", "\"moa\""),
    // aimux-core/src/moa.rs:64 `fn default_strip_reference_tools() -> bool { true }`.
    ("default_strip_reference_tools", "true"),
];

/// Directory under `generated/` holding the committed Swift output.
pub const COMMITTED: &str = "swift";

/// The Swift files for the current sources, paths relative to
/// `generated/swift/`.
///
/// # Errors
///
/// Extraction / IR errors and [`Swift::check`] refusals.
pub fn committed_outputs(inputs: &crate::manifest::Inputs) -> Result<Vec<Output>, Vec<String>> {
    let model = crate::wire::from_inputs(inputs)?;
    Swift::check(&model)?;
    Ok(Swift.emit(&model))
}

/// Files under `dir` that no output names (a stale or stray file is
/// reported by `--check` and removed by the plain run).
fn extra_files(dir: &std::path::Path, outputs: &[Output]) -> Vec<PathBuf> {
    let want: BTreeSet<PathBuf> = outputs.iter().map(|o| dir.join(&o.path)).collect();
    let mut stack = vec![dir.to_path_buf()];
    let mut extra = Vec::new();
    while let Some(d) = stack.pop() {
        let Ok(rd) = std::fs::read_dir(&d) else {
            continue;
        };
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                stack.push(p);
            } else if !want.contains(&p) {
                extra.push(p);
            }
        }
    }
    extra.sort();
    extra
}

/// Write the committed Swift under `<out_dir>/swift/`, removing files that
/// are no longer generated.
///
/// # Errors
///
/// See [`committed_outputs`]; plus I/O errors.
pub fn write_committed(
    inputs: &crate::manifest::Inputs,
    out_dir: &std::path::Path,
) -> Result<(), Vec<String>> {
    let outputs = committed_outputs(inputs)?;
    for o in &outputs {
        let path = out_dir.join(COMMITTED).join(&o.path);
        if let Some(d) = path.parent() {
            std::fs::create_dir_all(d).map_err(|e| vec![format!("{}: {e}", d.display())])?;
        }
        std::fs::write(&path, &o.content).map_err(|e| vec![format!("{}: {e}", path.display())])?;
    }
    for extra in extra_files(&out_dir.join(COMMITTED), &outputs) {
        std::fs::remove_file(&extra).map_err(|e| vec![format!("{}: {e}", extra.display())])?;
    }
    Ok(())
}

/// `--check`: the committed Swift equals a fresh emission.
///
/// # Errors
///
/// One `<path> is out of date` per stale or missing file.
pub fn check_committed(
    inputs: &crate::manifest::Inputs,
    out_dir: &std::path::Path,
) -> Result<(), Vec<String>> {
    let mut problems = Vec::new();
    let outputs = committed_outputs(inputs)?;
    for o in &outputs {
        let path = out_dir.join(COMMITTED).join(&o.path);
        match std::fs::read_to_string(&path) {
            Ok(t) if t == o.content => {}
            Ok(_) => problems.push(format!("{} is out of date", path.display())),
            Err(e) => problems.push(format!("{}: {e}", path.display())),
        }
    }
    for extra in extra_files(&out_dir.join(COMMITTED), &outputs) {
        problems.push(format!(
            "{} is not generated (extra file in generated/{COMMITTED})",
            extra.display()
        ));
    }
    if problems.is_empty() {
        Ok(())
    } else {
        Err(problems)
    }
}

impl Swift {
    /// What the Swift mapping refuses to emit.
    ///
    /// # Errors
    ///
    /// Every `u128`/`i128` use (no lossless Swift type; Go uses
    /// `json.Number`), every variant without a tag inside a tagged union,
    /// and every cycle of records holding each other by value or `Optional`
    /// (Swift structs cannot), one message each.
    pub fn check(model: &WireModel) -> Result<(), Vec<String>> {
        let mut errs = Vec::new();
        let g = Gen::new(model);
        for t in &model.types {
            let mut lists: Vec<(String, &[WireField])> = Vec::new();
            match &t.body {
                WireBody::Record { fields } => lists.push((t.name.clone(), fields)),
                WireBody::Union { variants, .. } => {
                    for v in variants {
                        if let VariantBody::Fields(fs) = &v.body {
                            lists.push((format!("{}::{}", t.name, v.rust), fs));
                        }
                    }
                }
                _ => {}
            }
            for (owner, fields) in lists {
                for f in fields {
                    errs.extend(g.skip_problem(&owner, f));
                }
            }
        }
        let mut edges: BTreeMap<&str, BTreeSet<String>> = BTreeMap::new();
        let records: BTreeSet<&str> = model
            .types
            .iter()
            .filter(|t| matches!(t.body, WireBody::Record { .. }))
            .map(|t| t.name.as_str())
            .collect();
        for t in &model.types {
            let mut tys: Vec<(String, &WireTy)> = Vec::new();
            match &t.body {
                WireBody::Record { fields } => {
                    for f in fields {
                        tys.push((format!("{}.{}", t.name, f.wire), &f.ty));
                        let direct = match &f.ty {
                            WireTy::Nullable(i) => i.as_ref(),
                            t => t,
                        };
                        if let WireTy::Named(n) = direct
                            && records.contains(n.as_str())
                        {
                            edges.entry(&t.name).or_default().insert(n.clone());
                        }
                    }
                }
                WireBody::Alias(a) => tys.push((t.name.clone(), a)),
                WireBody::StringEnum { .. } => {}
                WireBody::Union { repr, variants } => {
                    for v in variants {
                        if v.wire.is_none() && !matches!(repr, UnionRepr::Untagged) {
                            errs.push(format!(
                                "{}::{}: variant-level untagged variant in a tagged union is not supported by the Swift emitter",
                                t.name, v.rust
                            ));
                        }
                        match &v.body {
                            VariantBody::Unit => {}
                            VariantBody::Value(x) => {
                                tys.push((format!("{}::{}", t.name, v.rust), x));
                            }
                            VariantBody::Tuple(xs) => {
                                for x in xs {
                                    tys.push((format!("{}::{}", t.name, v.rust), x));
                                }
                            }
                            VariantBody::Fields(fs) => {
                                for f in fs {
                                    tys.push((format!("{}::{}.{}", t.name, v.rust, f.wire), &f.ty));
                                }
                            }
                        }
                    }
                }
            }
            for (at, ty) in tys {
                if has_128(ty) {
                    errs.push(format!(
                        "{at}: u128/i128 has no lossless Swift type; the Swift emitter refuses it"
                    ));
                }
            }
        }
        // By-value record cycles.
        for start in edges.keys() {
            let mut stack = vec![((*start).to_string(), vec![(*start).to_string()])];
            let mut seen = BTreeSet::new();
            while let Some((n, path)) = stack.pop() {
                for m in edges.get(n.as_str()).into_iter().flatten() {
                    if m == start {
                        errs.push(format!(
                            "record cycle by value: {} -> {m}",
                            path.join(" -> ")
                        ));
                    } else if seen.insert(m.clone()) {
                        let mut p = path.clone();
                        p.push(m.clone());
                        stack.push((m.clone(), p));
                    }
                }
            }
        }
        errs.sort();
        errs.dedup();
        if errs.is_empty() { Ok(()) } else { Err(errs) }
    }
}

fn has_128(t: &WireTy) -> bool {
    match t {
        WireTy::Prim(p) => p == "u128" || p == "i128",
        WireTy::Json | WireTy::Named(_) | WireTy::Literal(_) => false,
        WireTy::Array(i) | WireTy::Nullable(i) => has_128(i),
        WireTy::Map { key, value } => has_128(key) || has_128(value),
        WireTy::Tuple(xs) => xs.iter().any(has_128),
    }
}

