//! Phase 1 unit 1.8 acceptance: the generated ToolCall TypeScript has the
//! same wire as the current ts-rs file, the Go struct round-trips the same
//! JSON, and `--check` reports tampering.

use std::path::{Path, PathBuf};
use std::process::Command;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn tmp(label: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!(
        "aimux-codegen-{label}-{}-{:?}",
        std::process::id(),
        std::thread::current().id()
    ));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

fn copy_tree(from: &Path, to: &Path) {
    for entry in std::fs::read_dir(from).unwrap() {
        let entry = entry.unwrap();
        let target = to.join(entry.file_name());
        if entry.file_type().unwrap().is_dir() {
            std::fs::create_dir_all(&target).unwrap();
            copy_tree(&entry.path(), &target);
        } else {
            std::fs::copy(entry.path(), target).unwrap();
        }
    }
}

#[test]
fn committed_outputs_are_up_to_date() {
    aimux_codegen::check(&root().join("spec"), &root().join("generated")).unwrap();
}

/// Below the one-line generator header, the generated TypeScript is the
/// current `bindings/node/src/types/ToolCall.ts` line for line (same field
/// names, optionality, types, imports, docs).
#[test]
fn typescript_matches_the_current_binding_type() {
    let generated = std::fs::read_to_string(root().join("generated/ts/ToolCall.ts")).unwrap();
    let current =
        std::fs::read_to_string(root().join("../../bindings/node/src/types/ToolCall.ts")).unwrap();
    let body = |text: &str| text.split_once('\n').unwrap().1.to_string();
    assert!(current.starts_with("// This file was generated by [ts-rs]"));
    assert!(generated.starts_with(aimux_codegen::TS_HEADER));
    assert_eq!(body(&generated), body(&current));
}

fn assert_tamper_caught(relative: &str, edit: impl Fn(String) -> String) {
    let out = tmp(&relative.replace(['/', '.'], "_"));
    copy_tree(&root().join("generated"), &out);
    let file = out.join(relative);
    let text = std::fs::read_to_string(&file).unwrap();
    std::fs::write(&file, edit(text)).unwrap();

    let problems = aimux_codegen::check(&root().join("spec"), &out).unwrap_err();
    assert_eq!(problems.len(), 1, "{problems:?}");
    assert!(problems[0].contains(relative), "{problems:?}");

    let status = Command::new(env!("CARGO_BIN_EXE_aimux-codegen"))
        .args(["--check", "--out"])
        .arg(&out)
        .output()
        .unwrap();
    assert!(
        !status.status.success(),
        "--check accepted a tampered {relative}"
    );
    assert!(String::from_utf8_lossy(&status.stderr).contains("out of date"));
    let _ = std::fs::remove_dir_all(&out);
}

#[test]
fn check_rejects_tampered_typescript() {
    assert_tamper_caught("ts/ToolCall.ts", |t| {
        t.replace("dynamic?: boolean", "dynamic: boolean")
    });
}

#[test]
fn check_rejects_tampered_go() {
    assert_tamper_caught("go/tool_call.go", |t| {
        t.replace("\"toolName\"", "\"tool_name\"")
    });
}

#[test]
fn check_rejects_a_missing_file() {
    let out = tmp("missing");
    copy_tree(&root().join("generated"), &out);
    std::fs::remove_file(out.join("go/tool_call.go")).unwrap();
    assert!(aimux_codegen::check(&root().join("spec"), &out).is_err());
    let _ = std::fs::remove_dir_all(&out);
}

#[test]
fn check_passes_on_an_untouched_copy() {
    let out = tmp("clean");
    copy_tree(&root().join("generated"), &out);
    let status = Command::new(env!("CARGO_BIN_EXE_aimux-codegen"))
        .args(["--check", "--out"])
        .arg(&out)
        .status()
        .unwrap();
    assert!(status.success());
    let _ = std::fs::remove_dir_all(&out);
}

#[test]
fn spec_rejects_unknown_fields() {
    let err = aimux_codegen::parse_spec(r#"{"name":"X","doc":[],"fields":[],"extra":1}"#);
    assert!(err.is_err());
}

/// Wire samples serialized by aimux-core's `ToolCall`, decoded and
/// re-encoded by the generated Go struct, give the same JSON value. Needs a
/// local `go`; without one the test says so and returns.
#[test]
fn go_struct_round_trips_core_tool_call_json() {
    let samples = [
        r#"{"toolCallId":"c1","toolName":"weather","input":{"city":"Tokyo"}}"#,
        r#"{"toolCallId":"c2","toolName":"t","input":"Tokyo","providerExecuted":true,"dynamic":true}"#,
        r#"{"toolCallId":"c3","toolName":"t","input":{},"providerMetadata":{"openai":{"k":1}}}"#,
        r#"{"toolCallId":"c4","toolName":"t","input":"{\"a\":","dynamic":true,"invalid":true,"error":{"name":"AI_InvalidToolInputError","toolName":"t","toolInput":"{\"a\":","cause":"eof"}}"#,
    ];
    let core: Vec<String> = samples
        .iter()
        .map(|s| {
            let call: aimux_core::tool::ToolCall = serde_json::from_str(s).unwrap();
            serde_json::to_string(&call).unwrap()
        })
        .collect();

    if Command::new("go").arg("version").output().is_err() {
        eprintln!("SKIPPED: no `go` on PATH");
        return;
    }
    let dir = tmp("go");
    std::fs::copy(
        root().join("generated/go/tool_call.go"),
        dir.join("tool_call.go"),
    )
    .unwrap();
    std::fs::write(dir.join("go.mod"), "module aimuxgen\n\ngo 1.21\n").unwrap();
    let cases: String = core.iter().map(|s| format!("\t{s:?},\n")).collect();
    std::fs::write(
        dir.join("roundtrip_test.go"),
        format!(
            r#"package aimuxgen

import (
	"encoding/json"
	"reflect"
	"testing"
)

func TestRoundTrip(t *testing.T) {{
	for _, s := range []string{{
{cases}	}} {{
		var call ToolCall
		if err := json.Unmarshal([]byte(s), &call); err != nil {{
			t.Fatalf("%s: %v", s, err)
		}}
		out, err := json.Marshal(call)
		if err != nil {{
			t.Fatal(err)
		}}
		var a, b any
		_ = json.Unmarshal([]byte(s), &a)
		_ = json.Unmarshal(out, &b)
		if !reflect.DeepEqual(a, b) {{
			t.Fatalf("in  %s\nout %s", s, out)
		}}
	}}
}}
"#
        ),
    )
    .unwrap();
    let gofmt = Command::new("gofmt")
        .arg("-l")
        .arg(dir.join("tool_call.go"))
        .output()
        .unwrap();
    assert!(gofmt.stdout.is_empty(), "generated Go is not gofmt-clean");
    let test = Command::new("go")
        .args(["test", "./..."])
        .current_dir(&dir)
        .env("GOFLAGS", "-mod=mod")
        .env("GOTOOLCHAIN", "local")
        .output()
        .unwrap();
    assert!(
        test.status.success(),
        "{}\n{}",
        String::from_utf8_lossy(&test.stdout),
        String::from_utf8_lossy(&test.stderr)
    );
    let _ = std::fs::remove_dir_all(&dir);
}
